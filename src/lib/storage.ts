import { randomBytes } from "node:crypto";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { sseParams, storageConfigFromEnv, type StorageConfig } from "./storage-config";

// Private file storage for prescriptions (health data). Files are only ever served through
// permission-checked routes such as /api/prescriptions/[id]/file — never by public or presigned URL.
// - local: ./storage on disk (gitignored, outside /public), development only.
// - s3: a private S3 bucket (AWS Mumbai) or Cloudflare R2, with server-side encryption.

const ROOT = path.join(process.cwd(), "storage");
const KEY_PATTERN = /^prescriptions\/\d{4}\/[A-Za-z0-9_-]{24}\.(jpg|png|pdf)$/;
const CONTENT_TYPES = { jpg: "image/jpeg", png: "image/png", pdf: "application/pdf" } as const;

type Backend = { driver: "local" } | { driver: "s3"; config: Extract<StorageConfig, { driver: "s3" }>; client: S3Client };
let cached: Backend | null = null;

function backend(): Backend {
  if (cached) return cached;
  const config = storageConfigFromEnv(process.env);
  cached =
    config.driver === "local"
      ? { driver: "local" }
      : {
          driver: "s3",
          config,
          client: new S3Client({
            region: config.region,
            endpoint: config.endpoint,
            credentials: config.credentials,
            // R2 and most S3-compatible services want path-style addressing.
            forcePathStyle: !!config.endpoint,
          }),
        };
  return cached;
}

function checkKey(key: string): void {
  // Keys are generated by us; the pattern check also rules out path traversal.
  if (!KEY_PATTERN.test(key)) throw new Error("Invalid storage key");
}

function localPath(key: string): string {
  checkKey(key);
  return path.join(ROOT, ...key.split("/"));
}

export function newPrescriptionKey(ext: "jpg" | "png" | "pdf"): string {
  return `prescriptions/${new Date().getUTCFullYear()}/${randomBytes(18).toString("base64url")}.${ext}`;
}

export async function putObject(key: string, bytes: Uint8Array): Promise<void> {
  const b = backend();
  if (b.driver === "local") {
    const file = localPath(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, bytes, { flag: "wx" }); // never overwrite
    return;
  }
  checkKey(key);
  await b.client.send(
    new PutObjectCommand({
      Bucket: b.config.bucket,
      Key: key,
      Body: bytes,
      ContentType: CONTENT_TYPES[key.slice(key.lastIndexOf(".") + 1) as keyof typeof CONTENT_TYPES],
      IfNoneMatch: "*", // never overwrite
      ...sseParams(b.config.sse),
      // No ACL: the bucket's own policy keeps every object private.
    }),
  );
}

export async function getObject(key: string): Promise<Buffer> {
  const b = backend();
  if (b.driver === "local") return readFile(localPath(key));
  checkKey(key);
  const res = await b.client.send(new GetObjectCommand({ Bucket: b.config.bucket, Key: key }));
  if (!res.Body) throw new Error("Empty object body");
  return Buffer.from(await res.Body.transformToByteArray());
}

export async function deleteObject(key: string): Promise<void> {
  const b = backend();
  if (b.driver === "local") {
    await unlink(localPath(key)).catch(() => undefined);
    return;
  }
  checkKey(key);
  // An orphaned object is health data left behind, so make the failure visible (keys are random, not personal).
  await b.client
    .send(new DeleteObjectCommand({ Bucket: b.config.bucket, Key: key }))
    .catch((e: unknown) => console.error("Storage delete failed", key, e instanceof Error ? e.name : e));
}
