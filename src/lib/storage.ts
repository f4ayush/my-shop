import { randomBytes } from "node:crypto";
import { mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import path from "node:path";

// Private file storage. Only a local-disk driver exists so far, for development: files live in
// ./storage (gitignored, outside /public) and are only ever served through permission-checked routes.
// Production must use private object storage (e.g. S3/R2 in an Indian region) — not implemented yet.

const ROOT = path.join(process.cwd(), "storage");
const KEY_PATTERN = /^prescriptions\/\d{4}\/[A-Za-z0-9_-]{24}\.(jpg|png|pdf)$/;

function assertLocalAllowed() {
  const driver = process.env.STORAGE_DRIVER || "local";
  if (driver !== "local") throw new Error(`Storage driver "${driver}" is not implemented`);
  if (process.env.NODE_ENV === "production") {
    throw new Error("Local file storage is for development only. Configure private object storage.");
  }
}

function resolveKey(key: string): string {
  // Keys are generated by us; the pattern check also rules out path traversal.
  if (!KEY_PATTERN.test(key)) throw new Error("Invalid storage key");
  return path.join(ROOT, ...key.split("/"));
}

export function newPrescriptionKey(ext: "jpg" | "png" | "pdf"): string {
  return `prescriptions/${new Date().getUTCFullYear()}/${randomBytes(18).toString("base64url")}.${ext}`;
}

export async function putObject(key: string, bytes: Uint8Array): Promise<void> {
  assertLocalAllowed();
  const file = resolveKey(key);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, bytes, { flag: "wx" }); // never overwrite
}

export async function getObject(key: string): Promise<Buffer> {
  assertLocalAllowed();
  return readFile(resolveKey(key));
}

export async function deleteObject(key: string): Promise<void> {
  assertLocalAllowed();
  await unlink(resolveKey(key)).catch(() => undefined);
}
